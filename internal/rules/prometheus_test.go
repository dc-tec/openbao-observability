func alertExpression(t *testing.T, document prometheusRule, alertID string) string {
	t.Helper()
	for _, group := range document.Spec.Groups {
		for _, rule := range group.Rules {
			if rule.Alert == alertID {
				return rule.Expr
			}
		}
	}
	t.Fatalf("alert %s was not generated", alertID)
	return ""
}

type matcherExpectation struct {
	value       string
	matcherType promlabels.MatchType
}

func hasFunctionSelectorUnderBinaryOp(
	expression, function, metric string,
	expectedMatchers map[string]matcherExpectation,
	op parser.ItemType,
) bool {
	promQLParser := parser.NewParser(parser.Options{})
	parsed, err := promQLParser.ParseExpr(expression)
	if err != nil {
		return false
	}

	found := false
	parser.Inspect(parsed, func(node parser.Node, path []parser.Node) error {
		call, ok := node.(*parser.Call)
		if !ok || call.Func.Name != function || len(call.Args) != 1 || !hasBinaryOpAncestor(path, op) {
			return nil
		}

		selector, ok := call.Args[0].(*parser.VectorSelector)
		if !ok || selector.Name != metric || !hasExpectedMatchers(selector, expectedMatchers) {
			return nil
		}
		found = true
		return nil
	})
	return found
}

func hasFunctionCall(expression, function string) bool {
	promQLParser := parser.NewParser(parser.Options{})
	parsed, err := promQLParser.ParseExpr(expression)
	if err != nil {
		return false
	}

	found := false
	parser.Inspect(parsed, func(node parser.Node, _ []parser.Node) error {
		call, ok := node.(*parser.Call)
		if ok && call.Func.Name == function {
			found = true
		}
		return nil
	})
	return found
}

func hasSelectorUnderUnless(
	expression, metric string,
	expectedMatchers map[string]matcherExpectation,
) bool {
	promQLParser := parser.NewParser(parser.Options{})
	parsed, err := promQLParser.ParseExpr(expression)
	if err != nil {
		return false
	}

	found := false
	parser.Inspect(parsed, func(node parser.Node, path []parser.Node) error {
		selector, ok := node.(*parser.VectorSelector)
		if ok && selector.Name == metric &&
			hasExpectedMatchers(selector, expectedMatchers) &&
			hasBinaryOpAncestor(path, parser.LUNLESS) {
			found = true
		}
		return nil
	})
	return found
}

func hasSelectorMatcherType(expression, metric, matcherName string, matcherType promlabels.MatchType) bool {
	promQLParser := parser.NewParser(parser.Options{})
	parsed, err := promQLParser.ParseExpr(expression)
	if err != nil {
		return false
	}

	found := false
	parser.Inspect(parsed, func(node parser.Node, _ []parser.Node) error {
		selector, ok := node.(*parser.VectorSelector)
		if !ok || selector.Name != metric {
			return nil
		}
		for _, matcher := range selector.LabelMatchers {
			if matcher.Name == matcherName && matcher.Type == matcherType {
				found = true
			}
		}
		return nil
	})
	return found
}

func hasBinaryOpAncestor(path []parser.Node, op parser.ItemType) bool {
	for _, node := range path {
		if binary, ok := node.(*parser.BinaryExpr); ok && binary.Op == op {
			return true
		}
	}
	return false
}

func hasExpectedMatchers(selector *parser.VectorSelector, expected map[string]matcherExpectation) bool {
	for name, expectation := range expected {
		found := false
		for _, matcher := range selector.LabelMatchers {
			if matcher.Name == name && matcher.Value == expectation.value && matcher.Type == expectation.matcherType {
				found = true
				break
			}
		}
		if !found {
			return false
		}
	}
	return true
}

func TestRecordingRulesUseNormalizedIdentityGrouping(t *testing.T) {
	document := buildPrometheusRule(contracts.MetricContract{
		Normalization: contracts.Normalization{RecordingRulePrefix: "openbao"},
	}, "openbao")

	targetRecords := map[string]bool{
		"openbao:core_unsealed:min":              true,
		"openbao:core_in_flight_requests:max":    true,
		"openbao:autopilot_node_healthy:min":     true,
		"openbao:raft_storage_commit_index:max":  true,
		"openbao:raft_storage_applied_index:max": true,
		"openbao:raft_storage_apply_gap:max":     true,
		"openbao:raft_storage_fsm_pending:max":   true,
		"openbao:runtime_num_goroutines:max":     true,
		"openbao:runtime_alloc_bytes:max":        true,
		"openbao:runtime_heap_objects:max":       true,
		"openbao:runtime_sys_bytes:max":          true,
		"openbao:runtime_total_gc_pause_ns:max":  true,
		"openbao:runtime_total_gc_runs:max":      true,
	}

	seenTargets := map[string]bool{}
	for _, group := range document.Spec.Groups {
		for _, rule := range group.Rules {
			if !strings.Contains(rule.Expr, clusterIdentityGrouping) {
				t.Errorf("rule %s does not preserve cluster identity: %s", rule.Record, rule.Expr)
			}

			_, isTargetRule := targetRecords[rule.Record]
			hasTargetIdentity := strings.Contains(rule.Expr, targetIdentityGrouping)
			if isTargetRule != hasTargetIdentity {
				t.Errorf("rule %s target grouping = %t, want %t: %s", rule.Record, hasTargetIdentity, isTargetRule, rule.Expr)
			}
			if isTargetRule {
				seenTargets[rule.Record] = true
			}
		}
	}

	for record := range targetRecords {
		if !seenTargets[record] {
			t.Errorf("target rule %s was not generated", record)
		}
	}
}

