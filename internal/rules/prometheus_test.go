type recordingSample struct {
	labels map[string]string
	value  float64
}

func assertAggregateResults(t *testing.T, expression string, samples []recordingSample, want map[string]float64) {
	t.Helper()
	promQLParser := parser.NewParser(parser.Options{})
	parsed, err := promQLParser.ParseExpr(expression)
	if err != nil {
		t.Fatalf("parse PromQL expression %q: %v", expression, err)
	}
	aggregate, ok := parsed.(*parser.AggregateExpr)
	if !ok || aggregate.Without {
		t.Fatalf("expression is not a by-aggregate: %s", expression)
	}

	got := map[string]float64{}
	for _, sample := range samples {
		key := identityKey(aggregate.Grouping, sample.labels)
		value, exists := got[key]
		if !exists {
			got[key] = sample.value
			continue
		}
		switch aggregate.Op {
		case parser.SUM:
			got[key] = value + sample.value
		case parser.MIN:
			got[key] = min(value, sample.value)
		case parser.MAX:
			got[key] = max(value, sample.value)
		default:
			t.Fatalf("unsupported aggregate operation %s in %s", aggregate.Op, expression)
		}
	}

	if len(got) != len(want) {
		t.Fatalf("aggregate result count = %d, want %d: got %v, want %v", len(got), len(want), got, want)
	}
	for key, wantValue := range want {
		if gotValue, ok := got[key]; !ok || gotValue != wantValue {
			t.Errorf("aggregate result %q = %v, want %v", key, gotValue, wantValue)
		}
	}
}

func signalLabels(cluster, openbaoNamespace, scrapeProfile, pod, instance string) map[string]string {
	return map[string]string{
		"cluster":              cluster,
		"kubernetes_namespace": "secrets",
		"openbao_namespace":    openbaoNamespace,
		"scrape_profile":       scrapeProfile,
		"pod":                  pod,
		"instance":             instance,
	}
}

func clusterIdentityKey(labels map[string]string) string {
	return identityKey(strings.Split(clusterIdentityGrouping, ", "), labels)
}

func targetIdentityKey(labels map[string]string) string {
	return identityKey(strings.Split(targetIdentityGrouping, ", "), labels)
}

func identityKey(grouping []string, labels map[string]string) string {
	parts := make([]string, 0, len(grouping))
	for _, name := range grouping {
		parts = append(parts, name+"="+labels[name])
	}
	return strings.Join(parts, "|")
}

func recordingExpression(t *testing.T, document prometheusRule, record string) string {
	t.Helper()
	for _, group := range document.Spec.Groups {
		for _, rule := range group.Rules {
			if rule.Record == record {
				return rule.Expr
			}
		}
	}
	t.Fatalf("recording rule %s was not generated", record)
	return ""
}

func TestGenerateAlertRules(t *testing.T) {
	dir := t.TempDir()
	contractPath := filepath.Join(dir, "alerts.yaml")
	prometheusOutputPath := filepath.Join(dir, "prometheus-alerts.yaml")
	prometheusRuleFilePath := filepath.Join(dir, "prometheus-alert-rules.yaml")
	lokiOutputPath := filepath.Join(dir, "loki-alerts.yaml")

	if err := os.WriteFile(contractPath, []byte(alertContract()), 0o644); err != nil {
		t.Fatalf("write alert contract: %v", err)
	}

	err := GenerateAlertRules(GenerateAlertOptions{
		ContractPath:           contractPath,
		PrometheusOutputPath:   prometheusOutputPath,
		PrometheusRuleFilePath: prometheusRuleFilePath,
		LokiOutputPath:         lokiOutputPath,
		SourcePrefix:           "openbao",
	})
	if err != nil {
		t.Fatalf("GenerateAlertRules returned error: %v", err)
	}

	prometheusContent, err := os.ReadFile(prometheusOutputPath)
	if err != nil {
		t.Fatalf("read Prometheus output: %v", err)
	}
	prometheusText := string(prometheusContent)
	for _, fragment := range []string{
		"kind: PrometheusRule",
		"alert: OpenBaoNoActiveNode",
		"expr: openbao:core_active:sum == 0",
		"alert: OpenBaoMultipleActiveNodes",
		"expr: openbao:core_active:sum > 1",
		"alert: OpenBaoAutopilotFailureToleranceLost",
		"expr: openbao:raft_peers:max >= 3 and openbao:autopilot_failure_tolerance:max < 1",
		"component: raft",
		"alert: OpenBaoAuditResponseFailures",
		"expr: sum(increase(openbao_audit_log_response_failure[5m])) > 0",
		"runbook_url: https://github.com/dc-tec/openbao-observability/blob/main/docs/runbooks/no-active-openbao-leader.md",
	} {
		if !strings.Contains(prometheusText, fragment) {
			t.Fatalf("Prometheus alerts missing %q:\n%s", fragment, prometheusText)
		}
	}

	prometheusRuleFileContent, err := os.ReadFile(prometheusRuleFilePath)
	if err != nil {
		t.Fatalf("read Prometheus alert rule file: %v", err)
	}
	prometheusRuleFileText := string(prometheusRuleFileContent)
	for _, fragment := range []string{
		"groups:",
		"name: openbao.alerts",
		"alert: OpenBaoNoActiveNode",
		"expr: openbao:core_active:sum == 0",
		"alert: OpenBaoMultipleActiveNodes",
		"expr: openbao:core_active:sum > 1",
		"alert: OpenBaoAutopilotFailureToleranceLost",
		"expr: openbao:raft_peers:max >= 3 and openbao:autopilot_failure_tolerance:max < 1",
		"alert: OpenBaoAuditResponseFailures",
		"expr: sum(increase(openbao_audit_log_response_failure[5m])) > 0",
	} {
		if !strings.Contains(prometheusRuleFileText, fragment) {
			t.Fatalf("Prometheus alert rule file missing %q:\n%s", fragment, prometheusRuleFileText)
		}
	}
	if strings.Contains(prometheusRuleFileText, "kind: PrometheusRule") {
		t.Fatalf("native Prometheus alert rule file contains PrometheusRule wrapper:\n%s", prometheusRuleFileText)
	}

	lokiContent, err := os.ReadFile(lokiOutputPath)
	if err != nil {
		t.Fatalf("read Loki output: %v", err)
	}
	lokiText := string(lokiContent)
	for _, fragment := range []string{
		"kind: LokiAlertRules",
		"alert: OpenBaoAuditCanaryMissing",
		"expr: absent_over_time({log_stream=\"openbao.audit\"} | json request_path=\"request.path\" | " +
			"request_path=\"secret/data/observability/audit-canary\" [15m])",
	} {
		if !strings.Contains(lokiText, fragment) {
			t.Fatalf("Loki alerts missing %q:\n%s", fragment, lokiText)
		}
	}
}

